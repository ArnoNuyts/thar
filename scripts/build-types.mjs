import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

// The published entry point (`dist/main.js`) starts the TUI and exports
// nothing, so its declaration file is intentionally empty. Shipping it keeps
// editors from reporting a missing type definition and marks the package as
// typed on npm.
const outfile = fileURLToPath(new URL("../dist/main.d.ts", import.meta.url));

await mkdir(dirname(outfile), { recursive: true });
await writeFile(
  outfile,
  `// Generated by scripts/build-types.mjs. Do not edit.
export {};
`,
);
